-- การใช้ TRUNCATE CASCADE จะทำการลบข้อมูลในตารางที่ระบุ 
-- และลบข้อมูลในตารางอื่นที่มีการเชื่อมโยง (Foreign Key) กันออกทั้งหมดอย่างรวดเร็ว

TRUNCATE TABLE 
  connections, 
  devices, 
  subnets, 
  vlans, 
  racks, 
  rooms, 
  floors, 
  sites, 
  ports 
RESTART IDENTITY CASCADE;

-- หมายเหตุ: คำสั่งนี้จะไม่ลบตาราง (Tables) ทิ้งเหมือนคำสั่ง DROP
-- ทำให้ระบบยังสามารถเพิ่มข้อมูลใหม่ผ่านหน้าเว็บได้ตามปกติครับ
